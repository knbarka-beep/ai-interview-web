// Builds lib/knowledge.js (the cached system-prompt knowledge base) from the project version.
// Run: node scripts/build-knowledge.mjs [path-to-interview-project/knowledge]
// Budget: under 20k tokens. Measured on claude-haiku-5-5 this text runs at about 2.9 characters per token.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const src = process.argv[2] || "../interview-project/knowledge";

// Notes: title, core definition and sources only.
const notes = readdirSync(join(src, "notes"))
  .filter((f) => f.endsWith(".md"))
  .sort()
  .map((f) => {
    const t = readFileSync(join(src, "notes", f), "utf8");
    const title = t.match(/^# (.+)/m)[1];
    const def = t.match(/\*\*Core definition\.\*\* (.+)/)[1];
    const sources = t.match(/\*\*Sources\.\*\*\n([\s\S]+)$/)[1].trim();
    return `<note file="${f}" title="${title}">\n${def}\nSources:\n${sources}\n</note>`;
  })
  .join("\n");

// Question bank: question, model answer and source (key points are implied by the model answer).
const bank = readFileSync(join(src, "question_bank.md"), "utf8");
const questions = [...bank.matchAll(/### (Q\d+) \[([^\]|]+) \| (L\d)\]\n\*\*Question:\*\* (.+)\n\*\*Model answer:\*\* (.+)\n[\s\S]*?\*\*Source:\*\* (.+)/g)]
  .map(([, id, concept, level, q, a, s]) => `${id} [${concept.trim()} | ${level}] ${q}\nAnswer: ${a}\nSource: ${s}`)
  .join("\n\n");

const knowledge = `<notes>\n${notes}\n</notes>\n\n<question_bank>\n${questions}\n</question_bank>`;
writeFileSync("lib/knowledge.js", `// Generated by scripts/build-knowledge.mjs. Do not edit by hand.\nexport const KNOWLEDGE = ${JSON.stringify(knowledge)};\n`);
console.log(`knowledge: ${knowledge.length} chars, about ${Math.round(knowledge.length / 2.9)} tokens`);
